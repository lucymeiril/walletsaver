"""
WalletSavior 카테고리/키워드 데이터 입출력.

JSON export/import, DB seed SQL 생성, 병합 기능.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Optional

from .categories import CATEGORIES, get_category_tree, validate_tree
from .keywords import KEYWORDS


# ──────────────────────────────────────────────
# JSON Export
# ──────────────────────────────────────────────

def export_categories_json(filepath: Optional[str] = None) -> str:
    """
    전체 카테고리를 JSON 으로 내보내기.

    filepath 를 지정하면 파일로 저장, 아니면 JSON 문자열 반환.
    """
    tree = get_category_tree()
    data = {"categories": tree, "total_count": len(CATEGORIES)}
    json_str = json.dumps(data, ensure_ascii=False, indent=2)

    if filepath:
        Path(filepath).write_text(json_str, encoding="utf-8")

    return json_str


def export_categories_flat_json(filepath: Optional[str] = None) -> str:
    """카테고리를 flat 리스트 JSON 으로 내보내기."""
    data = {"categories": CATEGORIES, "total_count": len(CATEGORIES)}
